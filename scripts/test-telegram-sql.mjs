// Run with NU_PGLITE_PATH pointing to an installed @electric-sql/pglite package.
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(process.env.NU_PGLITE_PATH ? pathToFileURL(process.env.NU_PGLITE_PATH).href : '@electric-sql/pglite');
const db = new PGlite();
const owner='00000000-0000-4000-8000-000000000001', worker='00000000-0000-4000-8000-000000000002', other='00000000-0000-4000-8000-000000000003', task='00000000-0000-4000-8000-000000000004';
await db.exec(`
create role anon; create role authenticated; create role service_role bypassrls;
create schema auth;
create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
create table profiles(id uuid primary key,role text,is_active boolean);
create function nu_active_role() returns text language sql stable security definer as $$ select role from profiles where id=auth.uid() and is_active $$;
create table tasks(id uuid primary key,assignee_id uuid,created_by uuid,title text,status text,deadline timestamptz,expected_result text);
create table task_history(id bigint generated always as identity primary key,task_id uuid,user_id uuid,action text,old_value jsonb,new_value jsonb);
create table task_comments(id uuid primary key,task_id uuid,author_id uuid,body text);
create table recurring_task_templates(id uuid primary key,reminder_days integer[]);
create table recurring_task_instances(template_id uuid,task_id uuid);
insert into profiles values('${owner}','owner',true),('${worker}','manager',true),('${other}','manager',true);
insert into tasks values('${task}','${worker}','${owner}','Test task','new',now()+interval '2 days','Expected result');
`);
await db.exec(await readFile(new URL('../supabase/migrations/20260930010000_telegram.sql',import.meta.url),'utf8'));
const scalar=async (sql,params=[]) => (await db.query(sql,params)).rows[0].value;
await db.query(`insert into telegram_link_tokens(user_id,token_hash,expires_at) values($1,'test',now()+interval '10 minutes')`,[worker]);
assert.equal(await scalar("select nu_telegram_bind('test',123,'worker') as value"),true);
assert.equal(await scalar("select nu_telegram_bind('test',123,'worker') as value"),true,'Webhook replay must be idempotent');
assert.equal(await scalar("select nu_telegram_bind('test',456,'thief') as value"),false,'Consumed link must reject another chat');
await db.query(`insert into telegram_link_tokens(user_id,token_hash,expires_at) values($1,'expired',now()-interval '1 second')`,[other]);
assert.equal(await scalar("select nu_telegram_bind('expired',456,'other') as value"),false);
await db.query(`insert into telegram_links(user_id,chat_id) values($1,999)`,[owner]);
assert.equal(await scalar('select nu_telegram_visible($1,$2) as value',[other,task]),false,'Unrelated manager cannot see task');
await db.query(`insert into task_history(task_id,user_id,action,new_value) values($1,$2,'created','{}')`,[task,owner]);
assert.equal(await scalar('select count(*)::int as value from telegram_outbox'),1,'Notify assignee, exclude actor');
const claimed=(await db.query('select * from nu_telegram_claim(20)')).rows;
assert.equal(claimed.length,1);assert.equal(claimed[0].chat_id,123);
assert.equal((await db.query('select * from nu_telegram_claim(20)')).rows.length,0,'Active lease prevents double claim');
await db.query('select nu_telegram_finish($1,$2,200)',[claimed[0].id,owner]);
assert.equal(await scalar('select state as value from telegram_outbox where id=$1',[claimed[0].id]),'sending','Wrong lease cannot acknowledge');
await db.query('select nu_telegram_finish($1,$2,200)',[claimed[0].id,claimed[0].lease_id]);
assert.equal(await scalar('select state as value from telegram_outbox where id=$1',[claimed[0].id]),'sent');
await db.query(`insert into task_comments values(gen_random_uuid(),$1,$2,'Comment')`,[task,owner]);
await db.query('update profiles set is_active=false where id=$1',[worker]);
assert.equal((await db.query('select * from nu_telegram_claim(20)')).rows.length,0,'Disabled employee must not receive queued messages');
await db.query('update profiles set is_active=true where id=$1',[worker]);
const count=await scalar('select nu_telegram_reminders() as value');
const morning=await scalar("select ((now() at time zone 'Asia/Yekaterinburg')::time >= '08:00'::time) as value");
assert.equal(count,morning ? 1 : 0);
assert.equal(await scalar('select nu_telegram_reminders() as value'),0,'Same day reminders must not duplicate');
await db.query(`update tasks set deadline=deadline+interval '1 day' where id=$1`,[task]);
assert.equal((await db.query('select * from nu_telegram_claim(20)')).rows.length,0,'Changed deadline invalidates reminder');
await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${worker}',false);`);
assert.equal(await scalar('select count(*)::int as value from telegram_links'),1,'RLS exposes only own link');
await assert.rejects(db.query('select * from telegram_link_tokens'),/permission denied/);
await assert.rejects(db.query('select * from telegram_outbox'),/permission denied/);
await assert.rejects(db.query("select nu_telegram_bind('test',456,'thief')"),/permission denied/);
await assert.rejects(db.query('select * from nu_telegram_claim(20)'),/permission denied/);
await db.exec('reset role;');
await db.query('select nu_telegram_disconnect($1)',[worker]);
assert.equal(await scalar('select count(*)::int as value from telegram_links where user_id=$1',[worker]),0);
assert.equal(await scalar('select count(*)::int as value from telegram_link_tokens where user_id=$1',[worker]),0);
await db.close();
console.log('Telegram SQL: binding, replay, expiration, visibility, leases, disabled staff, reminder dedupe, deadline changes, RLS and disconnect passed.');
